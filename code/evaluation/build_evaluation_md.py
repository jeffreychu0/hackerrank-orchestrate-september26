"""Generate EVALUATION.md from the artifacts of the runs that actually happened.

Written rather than hand-maintained so the numbers cannot drift from the runs
they describe, and so the report always names the exact models it is reporting
on. Everything here reads files on disk; it makes no API calls.

    python code/evaluation/build_evaluation_md.py

Writes the same content to docs/EVALUATION.md and code/evaluation/EVALUATION.md.
"""

import argparse
import csv
import json
import re
from collections import Counter
from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path
import sys

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from harness.config import CODE_ROOT, DEFAULT_DATASET, REPORTS_DIR

M2M = REPORTS_DIR / "model_to_model"
SCORED = ("affordability_status", "recommended_payment_method", "payment_plan",
          "earliest_date_for_full_payment", "spending_changes_needed")
MISSING = "_not generated yet_"


def read_csv(path):
    path = Path(path)
    if not path.is_file():
        return {}
    with path.open(encoding="utf-8-sig") as handle:
        return {row["request_id"]: row for row in csv.DictReader(handle)}


def read_jsonl(path):
    path = Path(path)
    if not path.is_file():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()
            if line.strip()]


def read_json(path):
    path = Path(path)
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}


def usage_fields(path):
    """Pull the headline rows out of a generated usage report."""
    path = Path(path)
    if not path.is_file():
        return {}
    found = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|$", line)
        if match and not match.group(1).startswith("-"):
            found[match.group(1).strip()] = match.group(2).strip()
    return found


def sample_agreement(rows, truth):
    """Per-field agreement with the published answers, plus amount error."""
    if not rows:
        return None
    hits = dict.fromkeys(SCORED, 0)
    exact = 0
    error = Decimal(0)
    counted = 0
    for request_id, want in truth.items():
        got = rows.get(request_id)
        if not got:
            continue
        counted += 1
        for field in SCORED:
            hits[field] += got[field] == want[field]
        exact += all(got[field] == want[field] for field in SCORED)
        requested = Decimal(want["requested_amount"]) or Decimal(1)
        error += abs(Decimal(got["amount_safe_to_pay"])
                     - Decimal(want["amount_safe_to_pay"])) / requested
    if not counted:
        return None
    return {"hits": hits, "exact": exact, "counted": counted,
            "mean_relative_error": float(error / counted)}


def build(dataset_root):
    truth = read_csv(Path(dataset_root) / "sample_requests.csv")
    context = read_json(M2M / "run_context.json")
    calib_context = read_json(M2M / "calibration_context.json")
    verdicts = read_jsonl(M2M / "verdicts.jsonl")
    calibration = read_jsonl(M2M / "calibration.jsonl")
    rows = {p: read_csv(M2M / "rows_{}.csv".format(p))
            for p in ("openai", "anthropic")}
    run = usage_fields(CODE_ROOT / "evaluation" / "usage_report.md")
    models = context.get("models") or calib_context.get("models") or {}

    out = [
        "# Evaluation",
        "",
        "_Generated by `code/evaluation/build_evaluation_md.py` from the run "
        "artifacts on disk. Do not edit by hand; re-run the generator._",
        "",
        "Generated {} UTC.".format(
            datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")),
        "",
        "The solution is evaluated two ways, because the labelled data is small "
        "and agreeing with 25 rows is not the same as being right.",
        "",
        "| | Sample agreement | Cross-model adjudication |",
        "|---|---|---|",
        "| Question | Does it match the published answers? | Which of two independent readings of the evidence is better supported? |",
        "| Coverage | 25 labelled requests | any request in the dataset |",
        "| Needs ground truth | yes | no |",
        "| Tool | `code/evaluate_samples.py` | `code/evaluation/model_to_model/` |",
        "",
        "Neither evaluation feeds back into `output.csv`. Both are observational.",
        "",
    ]

    out += _submission_section(run)
    out += _distribution_section(
        read_csv(CODE_ROOT.parent / "output.csv"), truth)
    out += _sample_section(rows, truth, models)
    out += _adjudication_section(context, verdicts, models)
    out += _calibration_section(calib_context, calibration, models)
    out += _limits_section(verdicts, calibration)
    return "\n".join(out) + "\n"


def _submission_section(run):
    lines = ["## The submitted run", "",
             "`output.csv` is produced by `python code/main.py`, which defaults to "
             "the `openai` provider. The model reads the supplied messages and "
             "images and returns claims; every output field is computed by the "
             "deterministic engine.", ""]
    if not run:
        return lines + [MISSING, ""]
    keys = ["Run started (UTC)", "Provider", "Models used", "Evaluation requests",
            "Requests answered without any model call", "Total model calls",
            "Total tokens", "Average tokens per request",
            "Estimated total cost (USD)"]
    lines += ["| Property | Value |", "|---|---|"]
    for key in keys:
        if key in run:
            lines.append("| {} | {} |".format(key, run[key]))
    lines.append("")
    return lines


def _distribution_section(submitted, truth):
    """The only signal available about the 240-odd unlabelled rows."""
    lines = ["## 0. Shape of the submitted answers", "",
             "There is no ground truth for the evaluation requests, so the one "
             "check available on them is whether the mix of verdicts resembles "
             "the mix in the published samples. It is a weak signal - 25 rows "
             "give a wide margin - but a wildly different shape would be a "
             "warning.", ""]
    if not submitted or not truth:
        return lines + [MISSING, ""]
    statuses = ["affordable_now", "affordable_with_plan", "affordable_later",
                "not_affordable"]
    mine = Counter(row["affordability_status"] for row in submitted.values())
    theirs = Counter(row["affordability_status"] for row in truth.values())
    lines += ["| Status | output.csv ({} rows) | samples ({} rows) |"
              .format(len(submitted), len(truth)), "|---|---:|---:|"]
    for status in statuses:
        lines.append("| `{}` | {} ({:.0%}) | {} ({:.0%}) |".format(
            status, mine.get(status, 0), mine.get(status, 0) / len(submitted),
            theirs.get(status, 0), theirs.get(status, 0) / len(truth)))
    lines += ["",
              "The submitted run says `not_affordable` less often than the "
              "samples do. On the 25 samples themselves the harness gets every "
              "`not_affordable` row right, so this is either a real difference "
              "between the sample set and the evaluation set or a bias 25 rows "
              "are too few to reveal. It is not resolvable with the data "
              "supplied, and no threshold was tuned to close it.", ""]
    return lines


def _sample_section(rows, truth, models):
    lines = ["## 1. Agreement with the published samples", "",
             "The 25 supplied answers, scored per field. Both providers run the "
             "same prompt, schema and deterministic engine, so this measures the "
             "whole pipeline, not the model alone.", ""]
    scores = {p: sample_agreement(rows.get(p, {}), truth) for p in rows}
    scores = {p: s for p, s in scores.items() if s}
    if not scores:
        return lines + [MISSING, ""]
    names = list(scores)
    lines += ["| Field | " + " | ".join(_label(p, models) for p in names) + " |",
              "|---|" + "---:|" * len(names)]
    for field in SCORED:
        cells = ["{}/{}".format(scores[p]["hits"][field], scores[p]["counted"])
                 for p in names]
        lines.append("| `{}` | {} |".format(field, " | ".join(cells)))
    lines.append("| **all five fields exact** | {} |".format(" | ".join(
        "{}/{}".format(scores[p]["exact"], scores[p]["counted"]) for p in names)))
    lines.append("| mean relative error on `amount_safe_to_pay` | {} |".format(
        " | ".join("{:.4f}".format(scores[p]["mean_relative_error"]) for p in names)))
    lines.append("")

    identical = sum(1 for request_id in truth
                    if all(rows[p].get(request_id) for p in names)
                    and len({tuple(sorted(rows[p][request_id].items()))
                             for p in names}) == 1)
    if len(names) == 2:
        lines += ["{} of {} rows are byte-identical across the two providers. "
                  "That convergence is the deterministic engine doing its job: "
                  "swapping the model barely moves the output."
                  .format(identical, len(truth)), ""]
    return lines


def _adjudication_section(context, verdicts, models):
    lines = ["## 2. Cross-model adjudication", "",
             "Both providers read each request's evidence independently, then "
             "each grades both readings blind, in a per-request randomised "
             "order, with no vendor name anywhere in the prompt. Because every "
             "item is judged in both directions, self-preference is measured "
             "rather than assumed.", ""]
    if not verdicts:
        return lines + [MISSING, ""]
    summary = context.get("summary") or {}
    if summary:
        lines += ["| Eval set | Count |", "|---|---:|"]
        for key, value in summary.items():
            lines.append("| {} | {} |".format(key.replace("_", " "), value))
        lines.append("")

    judges = sorted({v["judge"] for v in verdicts})
    producers = [p for p in ("openai", "anthropic") if p in models] or judges
    lines += ["| Judge | Items | " +
              " | ".join("prefers {}".format(p) for p in producers) +
              " | equivalent | neither |",
              "|---|---:|" + "---:|" * (len(producers) + 2)]
    for judge in judges:
        pool = [v for v in verdicts if v["judge"] == judge]
        counts = Counter(v["winner"] for v in pool)
        lines.append("| {} | {} | {} | {} | {} |".format(
            _label(judge, models), len(pool),
            " | ".join(str(counts.get(p, 0)) for p in producers),
            counts.get("equivalent", 0), counts.get("neither", 0)))
    lines.append("")

    gaps = _self_preference(verdicts, producers)
    decided = Counter(v["judge"] for v in verdicts if v["winner"] in producers)
    lines += ["**Self-preference.** A judge that rates its own reading higher "
              "than the other judge rates that same reading is showing bias.", "",
              "| Reading by | Preferred by itself | Preferred by the other judge | Gap |",
              "|---|---:|---:|---:|"]
    for producer, stats in gaps.items():
        lines.append("| {} | {} | {} | {} |".format(
            producer, _pct(stats[0]), _pct(stats[1]), _signed(stats[2])))
    lines += ["",
              "Computed over the items where a judge picked a side at all: {}. "
              "That is a small base - treat the gap as an order of magnitude, "
              "not a measurement, and note it moves between runs."
              .format(", ".join("{} {}".format(j, n) for j, n in sorted(decided.items()))),
              ""]

    missed = Counter()
    for verdict in verdicts:
        for item in verdict.get("missed_by_both", []):
            missed[" ".join(str(item).split())[:120]] += 1
    if missed:
        lines += ["**Facts both readings missed.** Flagged by a judge against "
                  "both readings at once, so no provider choice fixes them. "
                  "These are the prompt and vocabulary candidates.", ""]
        for text, count in missed.most_common(6):
            lines.append("- ({}x) {}".format(count, text))
        lines.append("")
    return lines


def _calibration_section(context, calibration, models):
    lines = ["## 3. Are the judges any good?", "",
             "Cross-examination alone cannot answer this. Each item pairs a real "
             "reading against the same reading damaged in one known way, so the "
             "correct verdict is known by construction. These are the failure "
             "modes deterministic validation cannot catch: `harness/facts.py` "
             "already refuses an unknown source, an unowned event, an invented "
             "category or an impossible date, but nothing in code can tell that "
             "`next_occurrence` was quietly promoted to `ongoing`.", "",
             'A verdict of "equivalent" counts as a miss.', ""]
    if not calibration:
        return lines + [MISSING, ""]
    judges = sorted({record["judge"] for record in calibration})
    defects = []
    for record in calibration:
        if record["defect"] not in defects:
            defects.append(record["defect"])
    lines += ["| Defect | " + " | ".join(_label(j, models) for j in judges) + " |",
              "|---|" + "---:|" * len(judges)]
    totals = dict.fromkeys(judges, [0, 0])
    for defect in defects:
        cells = []
        for judge in judges:
            pool = [r for r in calibration
                    if r["judge"] == judge and r["defect"] == defect]
            caught = sum(1 for r in pool if r["resolved"] == "clean")
            totals[judge] = [totals[judge][0] + caught, totals[judge][1] + len(pool)]
            cells.append("{}/{}".format(caught, len(pool)))
        lines.append("| `{}` | {} |".format(defect, " | ".join(cells)))
    lines.append("| **total** | {} |".format(" | ".join(
        "{}/{} ({:.0%})".format(totals[j][0], totals[j][1],
                                totals[j][0] / totals[j][1] if totals[j][1] else 0)
        for j in judges)))
    lines.append("")

    misses = [r for r in calibration if r["resolved"] != "clean"]
    if misses:
        lines += ["Misses:", ""]
        for record in misses:
            lines.append("- `{}` on {} ({}): judge said **{}**".format(
                record["defect"], record["request_id"], record["judge"],
                record["resolved"]))
        lines.append("")
    return lines


def _limits_section(verdicts, calibration):
    lines = ["## What these numbers do not show", ""]
    if verdicts:
        # Each item is judged once per provider, so count distinct requests.
        by_request = {v["request_id"]: v for v in verdicts}
        changed = sum(1 for v in by_request.values() if v.get("row_fields_differ"))
        differ = sum(1 for v in by_request.values() if v.get("claims_differ"))
        lines.append(
            "- **Most provider disagreement is cosmetic.** Of the adjudicated "
            "items, {} had differing claim sets but only {} had any differing "
            "output field. The judges are mostly comparing wording, scope "
            "metadata and certainty labels.".format(differ, changed))
    lines += [
        "- **Adjudication is not correctness.** A preferred reading is one a "
        "peer model found better supported by the evidence. On the sample set "
        "the two providers produce the same row often enough that there is "
        "almost never a case where exactly one was right, so preference cannot "
        "be checked against ground truth. That is why section 3 exists.",
        "- **The judges share a blind spot with the producers.** A fact both "
        "readings miss and neither judge flags is invisible to this method.",
        "- **The calibration set is small and synthetic.** It measures "
        "sensitivity to defects chosen in advance, not to unknown ones.",
        "- **Sample agreement is 25 rows.** Differences of one or two rows are "
        "noise, and the remaining gaps there are forecast-threshold effects "
        "rather than rule errors - see `docs/HARNESS.md`.",
        "",
    ]
    return lines


def _self_preference(verdicts, producers):
    decided = {}
    for verdict in verdicts:
        if verdict["winner"] in producers:
            decided.setdefault(verdict["judge"], []).append(verdict["winner"])
    result = {}
    for producer in producers:
        rates = {}
        for judge, pool in decided.items():
            rates[judge] = sum(1 for w in pool if w == producer) / len(pool)
        own = rates.get(producer)
        other = next((r for j, r in rates.items() if j != producer), None)
        result[producer] = (own, other,
                            None if own is None or other is None else own - other)
    return result


def _label(provider, models):
    model = (models or {}).get(provider)
    return "{} (`{}`)".format(provider, model) if model else provider


def _pct(value):
    return "n/a" if value is None else "{:.0%}".format(value)


def _signed(value):
    return "n/a" if value is None else "{:+.0%}".format(value)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--targets", type=Path, nargs="*", default=None)
    args = parser.parse_args(argv)

    text = build(args.dataset)
    targets = args.targets or [CODE_ROOT.parent / "docs" / "EVALUATION.md",
                               CODE_ROOT / "evaluation" / "EVALUATION.md"]
    for target in targets:
        Path(target).parent.mkdir(parents=True, exist_ok=True)
        Path(target).write_text(text, encoding="utf-8")
        print("wrote {}".format(target))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
